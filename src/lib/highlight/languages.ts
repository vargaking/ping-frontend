/** The registered name for a block's language, or null (unknown, missing, not a string). */
export function knownLanguage(raw: unknown): string | null {
	if (typeof raw !== 'string') return null;
	const key = raw.trim().toLowerCase();
	return Object.hasOwn(LANGUAGES, key) ? LANGUAGES[key] : null;
}
